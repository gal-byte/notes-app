// A group's colored square with its icon. Older groups made with
// an emoji (before icons) keep showing their emoji.
function groupBadge(group, size = '') {
  const inner = group.icon ? icon(group.icon) : `<span class="badge-emoji">${escapeHtml(group.emoji || '')}</span>`;
  return `<span class="badge ${size} t-${group.tint || 'slate'}">${inner}</span>`;
}

